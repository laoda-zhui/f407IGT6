#include "Delay.h"

/**************************************************************************
	使用m内核的dwt计数器
**************************************************************************/



/**************************************************************************
函数功能：初始化DWT周期计数器
入口参数：无
返回  值：1: 初始化成功; 0: 初始化失败（芯片可能不支持DWT） f407igt6_168mhz:最大安全延时约为25.5秒
**************************************************************************/
uint8_t My_Delay_Init(void)
{
    // 1. 使能DWT的跟踪功能（访问DWT寄存器的前提）
    CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;

    // 2. 清除周期计数器
    DWT->CYCCNT = 0;

    // 3. 使能周期计数器
    DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;

    // 4. 验证DWT计数器是否已成功启用（可选但推荐）
    // 简单测试：延时几个周期后查看计数器是否增长
    uint32_t start = DWT->CYCCNT;
    volatile uint32_t test_counter = 0;
    for(uint32_t i = 0; i < 100; i++) {
        test_counter++; // 防止循环被优化
    }

    return (DWT->CYCCNT > start); // 如果计数器增长，说明初始化成功
}


/**************************************************************************
函数功能：DWT-us延时
入口参数：无
返回  值：无
**************************************************************************/
void My_Delayus(uint32_t us)
{
    uint32_t start = DWT->CYCCNT;
    uint32_t cycles = us * (SystemCoreClock / 1000000);
    while((DWT->CYCCNT - start) < cycles);
}


/**************************************************************************
函数功能：DWT-ms延时
入口参数：无
返回  值：无
**************************************************************************/
void My_Delayms(uint32_t ms)
{
    uint32_t start = DWT->CYCCNT;
    uint32_t cycles = ms * (SystemCoreClock / 1000);
    while((DWT->CYCCNT - start) < cycles);
}









