/**************************************************************************
函数功能：将单个字符变量用16进制转换成数字
入口参数：无
返回  值：数字
**************************************************************************/
uint8_t CharToHex(char c)
{
    if (c >= '0' && c <= '9') return c - '0';      // '0'-'9' 转为 0-9
    if (c >= 'A' && c <= 'F') return c - 'A' + 10; // 'A'-'F' 转为 10-15
    if (c >= 'a' && c <= 'f') return c - 'a' + 10; // 'a'-'f' 转为 10-15
    return 0; // 如果不是十六进制字符，返回0
}


