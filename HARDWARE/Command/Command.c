/**************************************************************************
函数功能：命令-LED标志物显示超声波测距
入口参数：无
返回  值：无
**************************************************************************/
void Command_LEDShowDis(void)
{
	uint8_t TxBuf[8]={0x55,0x04,0x04,0x00,0x00,0x00,0x00,0xBB};
	uint16_t Dis_mm;
	uint8_t bai,shi,ge;

	Dis_mm = (uint16_t)(Distance*10.0);
	if(Dis_mm>999){Dis_mm = 999;}

    // 3. 提取百、十、个位
    bai = Dis_mm / 100;
    shi = (Dis_mm % 100) / 10;
    ge  = Dis_mm % 10;

	TxBuf[4] = bai;
	TxBuf[5] = (shi << 4) | ge ;

	TxBuf[6] = (TxBuf[2] + TxBuf[3] + TxBuf[4] + TxBuf[5])%256;

	CAN_TxtoZigbee(TxBuf, 8);

}


